// Compiles knowledge/ + data/ into one importable module (src/kb.generated.js) so the
// server bundles cleanly on Vercel and runs from `npx github:` without a build step.
// Also writes the plain-text mirrors the GitHub Pages site serves (taste.md, llms.txt).
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync } from 'node:fs';
import { join, basename, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const K = join(root, 'knowledge');
const read = (p) => readFileSync(p, 'utf8');
const json = (name, fallback) => (existsSync(join(K, name)) ? JSON.parse(read(join(K, name))) : fallback);

// Guide order is the reading order on the site and in taste.md.
const GUIDE_ORDER = [
  'core', 'workflow', 'anti-slop', 'typography', 'color', 'layout-spacing', 'layouts',
  'motion', 'gsap-scroll', 'components', 'states-accessibility', 'responsive-mobile',
  'native-feel', 'dark-mode-dataviz', 'imagery-texture', 'copy', 'design-md',
  'dimensional-drawing', 'review',
];

const guides = {};
for (const file of readdirSync(K).filter((f) => f.endsWith('.md'))) {
  const id = basename(file, '.md');
  const body = read(join(K, file)).trim();
  const title = (body.match(/^#\s+(.+)$/m) || [, id])[1].trim();
  const summary = (body.match(/^>\s*(?!Condensed)(.+)$/m) || [, ''])[1].trim();
  guides[id] = { id, title, summary, body };
}
const order = [...GUIDE_ORDER.filter((id) => guides[id]), ...Object.keys(guides).filter((id) => !GUIDE_ORDER.includes(id)).sort()];

// Minimal RFC 4180 CSV parser (quoted fields, escaped quotes, newlines inside quotes).
function parseCsv(text) {
  const rows = [];
  let row = [], field = '', q = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (c === '"') q = false;
      else field += c;
    } else if (c === '"') q = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n' || c === '\r') {
      if (c === '\r' && text[i + 1] === '\n') i++;
      row.push(field); field = '';
      if (row.some((v) => v !== '')) rows.push(row);
      row = [];
    } else field += c;
  }
  if (field !== '' || row.length) { row.push(field); rows.push(row); }
  const [head, ...body] = rows;
  return body.map((r) => Object.fromEntries(head.map((h, i) => [h.trim(), (r[i] ?? '').trim()]).filter(([h, v]) => h !== 'No' && v !== '')));
}

const U = join(root, 'data', 'uupm');
const DB_FILES = {
  product: 'products', style: 'styles', color: 'colors', typography: 'typography', landing: 'landing',
  ux: 'ux-guidelines', chart: 'charts', motion: 'motion', app: 'app-interface', reasoning: 'ui-reasoning',
  icons: 'icons', 'react-perf': 'react-performance',
};
const db = {};
for (const [domain, file] of Object.entries(DB_FILES)) db[domain] = parseCsv(read(join(U, `${file}.csv`)));
db.stacks = {};
for (const f of readdirSync(join(U, 'stacks')).filter((f) => f.endsWith('.csv'))) db.stacks[basename(f, '.csv')] = parseCsv(read(join(U, 'stacks', f)));

const kb = {
  builtAt: new Date().toISOString().slice(0, 10),
  instructions: existsSync(join(K, 'instructions.txt')) ? read(join(K, 'instructions.txt')).trim() : '',
  order,
  guides,
  directions: json('directions.json', []),
  detectors: json('detectors.json', []),
  components: json('components.json', []),
  brands: json('brands.json', []),
  sources: json('sources.json', []),
  db,
};

writeFileSync(join(root, 'src', 'kb.generated.js'), `// Generated by scripts/build-kb.mjs from knowledge/ and data/. Do not edit by hand.\nexport default ${JSON.stringify(kb)};\n`);

// Site mirrors: one long-form file an agent can read by URL, plus an llms.txt index.
const site = join(root, 'site');
if (!existsSync(site)) mkdirSync(site);
const SITE = 'https://kamal007olica.github.io/taste-mcp';
writeFileSync(join(site, 'taste.md'), order.map((id) => guides[id].body).join('\n\n---\n\n') + '\n');
writeFileSync(join(site, 'llms.txt'), [
  '# Taste MCP',
  '',
  '> Design taste for coding agents, condensed from 14 open-source design repos. Add the MCP (https://agent-taste.vercel.app/mcp) or read the guides below before building UI.',
  '',
  '## Guides',
  ...order.map((id) => `- [${guides[id].title}](${SITE}/guides/${id}.md)`),
  '',
  '## Full text',
  `- [taste.md](${SITE}/taste.md): every guide in one file`,
  '',
].join('\n'));
const gdir = join(site, 'guides');
if (!existsSync(gdir)) mkdirSync(gdir);
for (const id of order) writeFileSync(join(gdir, `${id}.md`), guides[id].body + '\n');
writeFileSync(join(site, 'kb.json'), JSON.stringify({
  order, guides: Object.fromEntries(order.map((id) => [id, { title: guides[id].title, summary: guides[id].summary }])),
  directions: kb.directions, sources: kb.sources,
  counts: { guides: order.length, detectors: kb.detectors.length, components: kb.components.length, brands: kb.brands.length, directions: kb.directions.length, dbRows: Object.values(DB_FILES).length && Object.entries(db).reduce((n, [k, v]) => n + (k === 'stacks' ? Object.values(v).reduce((a, r) => a + r.length, 0) : v.length), 0) },
}));

// ---- Site pages: guide HTML, plus build-time injection into index.html ----
const { marked } = await import('marked');
const { audit } = await import('../src/audit.js');
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const FONTS = 'https://fonts.googleapis.com/css2?family=Gloock&family=IBM+Plex+Mono:wght@400;500&family=Schibsted+Grotesk:wght@400;500;600&display=swap';

order.forEach((id, i) => {
  const g = guides[id];
  const prev = guides[order[i - 1]], next = guides[order[i + 1]];
  const html = marked.parse(g.body.replace(/\s—\s/g, ', '));
  writeFileSync(join(gdir, `${id}.html`), `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>${esc(g.title)} · Taste MCP</title><meta name="description" content="${esc(g.summary || g.title)}">
<meta name="color-scheme" content="light dark"><link rel="icon" href="../favicon.svg" type="image/svg+xml">
<link rel="preconnect" href="https://fonts.googleapis.com"><link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link href="${FONTS}" rel="stylesheet"><link rel="stylesheet" href="../assets/site.css">
<link rel="alternate" type="text/markdown" href="${id}.md"></head>
<body><main class="doc"><a class="back" href="../#guides">← taste</a><a class="raw" href="${id}.md">Markdown</a>
${html}
<nav class="doc-nav" aria-label="Guides">${prev ? `<a href="${prev.id}.html">← ${esc(prev.title)}</a>` : '<span></span>'}${next ? `<a href="${next.id}.html">${esc(next.title)} →</a>` : ''}</nav>
<p class="fineprint">Read by your agent through <code>get_guide("${id}")</code> in the taste MCP.</p></main></body></html>
`);
});

const indexPath = join(site, 'index.html');
let index = read(indexPath);
const inject = (name, content) => {
  index = index.replace(new RegExp(`(<!--${name}:start-->)[\\s\\S]*?(<!--${name}:end-->)`), `$1\n${content}\n$2`);
};

inject('sources', kb.sources.map((s) => `      <li><span class="src-n">${s.n}</span><span class="src-name"><a href="${s.repo}">${esc(s.name)}</a></span><span class="src-gives">${esc(s.gives)}</span><span class="src-meta">★ ${s.stars} · ${esc(s.license)}</span></li>`).join('\n'));

if (guides.core) {
  const groups = guides.core.body.split(/^## /m).slice(1).map((chunk) => {
    const [heading, ...rest] = chunk.split('\n');
    const items = rest.join('\n').match(/^\d+\.\s.+$/gm) || [];
    return { heading: heading.trim(), start: Number(items[0]?.match(/^(\d+)/)[1] || 1), items: items.map((l) => marked.parseInline(l.replace(/^\d+\.\s/, ''))) };
  });
  inject('rules', `    <div class="rule-groups">\n${groups.map((g) => `      <div class="rule-group"><h3>${esc(g.heading)}</h3><ol style="--start:${g.start - 1}">${g.items.map((it) => `<li><span>${it}</span></li>`).join('')}</ol></div>`).join('\n')}\n    </div>`);
}

inject('guides', order.map((id) => `      <li><a href="guides/${id}.html"><b>${esc(guides[id].title)}</b><span>${esc(clipText(guides[id].summary, 110))}</span></a></li>`).join('\n'));
function clipText(s, n) { return s && s.length > n ? `${s.slice(0, n - 1).replace(/\s+\S*$/, '')}…` : s || ''; }

const selfCss = read(join(site, 'assets', 'site.css')).replace(/\/\* before:start[\s\S]*?before:end \*\//, '');
const selfScore = (html) => audit(html.replace(/<script id="kb-data"[\s\S]*?<\/script>/, '') + selfCss + read(join(site, 'assets', 'site.js')), kb.detectors).score;
const counts = { directions: kb.directions.length, detectors: kb.detectors.length, components: kb.components.length, brands: kb.brands.length, guides: order.length };
counts.self = selfScore(index);
index = index.replace(/<!--count:(\w+)-->[^<]*<!--\/count-->/g, (m, k) => `<!--count:${k}-->${counts[k] ?? '?'}<!--/count-->`);

// Score the two demo panes with the real audit: their markup plus their CSS block.
const css = read(join(site, 'assets', 'site.css'));
const block = (name) => (css.match(new RegExp(`/\\* ${name}:start[\\s\\S]*?${name}:end \\*/`)) || [''])[0];
const pane = (name) => (index.match(new RegExp(`<!--pane:${name}-->[\\s\\S]*?<!--/pane:${name}-->`)) || [''])[0];
const scoreBefore = audit(pane('before') + block('before'), kb.detectors).score;
const scoreAfter = audit(pane('after') + block('after'), kb.detectors).score;

const demo = kb.directions.find((d) => d.id === 'stationery-desk') || kb.directions.find((d) => (d.bestFor || []).some((b) => /fintech|finance|invoic/i.test(b))) || kb.directions[0];
const siteData = {
  audit: { before: scoreBefore, after: scoreAfter },
  demoDirection: demo?.id,
  directions: kb.directions.map(({ id, name, genre, signature, type, palette, shape }) => ({ id, name, genre, signature, type: { display: type?.display, body: type?.body, googleFonts: type?.googleFonts }, palette, shape: { radius: shape?.radius } })),
};
index = index.replace(/(<script id="kb-data" type="application\/json">)[\s\S]*?(<\/script>)/, `$1${JSON.stringify(siteData).replace(/</g, '\\u003c')}$2`);
writeFileSync(indexPath, index);
console.log(`site: demo audit before ${scoreBefore}, after ${scoreAfter}; self-audit ${counts.self}; demo direction ${demo?.id}`);

console.log(`kb: ${order.length} guides, ${kb.directions.length} directions, ${kb.detectors.length} detectors, ${kb.components.length} components, ${kb.brands.length} brands, db ${Object.keys(DB_FILES).length} domains + ${Object.keys(db.stacks).length} stacks`);
